//! Render the static PCI registry for people and host tooling.
use anyhow::{Context, Result, ensure};
use clap::Args;
use serde::Serialize;
use std::{fmt::Write, fs, path::PathBuf};
use stela_drivers::gpu::nouveau_chip::{Architecture, CHIPS};
use stela_drivers::probe::registry::{self, Class, Firmware, LicenseTier, Manifest, Status};
use stela_loader::host_firmware::{recipes, requirements::Inventory};

#[derive(Args)]
pub struct Catalog {
    /// Output directory, defaulting to the repository root.
    #[arg(long)]
    output_dir: Option<PathBuf>,
    /// Verify that the existing output matches the registry.
    #[arg(long)]
    check: bool,
}

#[derive(Serialize)]
struct Document {
    abi: (u16, u16),
    modules: Vec<Row>,
    nvmodern_chipsets: Vec<NouveauChip>,
}

#[derive(Serialize)]
struct NouveauChip {
    chipset: String,
    name: &'static str,
    architecture: &'static str,
    display: bool,
    firmware: Vec<String>,
}

#[derive(Serialize)]
struct Row {
    id: &'static str,
    implementation: &'static str,
    class: &'static str,
    status: &'static str,
    source: &'static str,
    license: &'static str,
    tier: &'static str,
    firmware: &'static [&'static str],
    firmware_profile: Option<&'static str>,
}

impl From<&Manifest> for Row {
    fn from(manifest: &Manifest) -> Self {
        let class = match manifest.class {
            Class::Storage => "storage",
            Class::Ethernet => "ethernet",
            Class::Wifi => "wifi",
            Class::Bluetooth => "bluetooth",
            Class::Audio => "audio",
            Class::Input => "input",
            Class::UsbHost => "usb-host",
            Class::Gpu => "gpu",
            Class::Platform => "platform",
        };
        let status = match manifest.status {
            Status::Implemented => "implemented",
            Status::CheckOnly => "check-only",
        };
        let tier = match manifest.license.tier {
            LicenseTier::A => "A",
            LicenseTier::B => "B",
        };
        let (firmware, firmware_profile) = match manifest.firmware {
            Firmware::None => (&[][..], None),
            Firmware::Required(files) => (files, None),
            Firmware::ProfileSelected(profile) => (&[][..], Some(profile)),
        };
        Self {
            id: manifest.id,
            implementation: manifest.implementation,
            class,
            status,
            source: manifest.source,
            license: manifest.license.spdx,
            tier,
            firmware,
            firmware_profile,
        }
    }
}

fn document() -> Result<Document> {
    let nvmodern_chipsets = CHIPS
        .iter()
        .map(|chip| {
            let mut inventory = Inventory::default();
            recipes::require_gsp(&mut inventory, &chip.name.to_ascii_lowercase())
                .with_context(|| format!("matching the GSP recipes for {}", chip.name))?;
            let architecture = match chip.architecture {
                Architecture::Turing => "Turing",
                Architecture::Ampere => "Ampere",
                Architecture::Ada => "Ada",
                Architecture::Hopper => "Hopper",
                Architecture::Blackwell => "Blackwell",
            };
            Ok(NouveauChip {
                chipset: format!("0x{:03x}", chip.chipset),
                name: chip.name,
                architecture,
                display: chip.display,
                firmware: inventory
                    .requests()
                    .iter()
                    .map(|request| request.name.clone())
                    .collect(),
            })
        })
        .collect::<Result<_>>()?;
    Ok(Document {
        abi: registry::ABI,
        modules: registry::manifests().map(Row::from).collect(),
        nvmodern_chipsets,
    })
}

fn markdown(document: &Document) -> String {
    let mut output = String::from(
        "# Northwood PCI driver registrations\n\n\
         Generated by `cargo xtask catalog`. An implementation or identity match establishes a candidate for boot-time probing. Hardware verification is recorded in `hardware/`.\n\n\
         | Module | Implementation | Class | Status | Source | Source license | Tier | Host firmware |\n\
         | --- | --- | --- | --- | --- | --- | --- | --- |\n",
    );
    for row in &document.modules {
        let firmware = if let Some(profile) = row.firmware_profile {
            format!("Selected by {profile}")
        } else if row.firmware.is_empty() {
            String::from("—")
        } else {
            row.firmware.join(", ")
        };
        writeln!(
            output,
            "| `{}` | `{}` | {} | {} | [source]({}) | `{}` | {} | {} |",
            row.id,
            row.implementation,
            row.class,
            row.status,
            row.source,
            row.license,
            row.tier,
            firmware,
        )
        .expect("writing to a string cannot fail");
    }
    output.push_str(
        "\n## NVModern chipset profiles\n\n\
         The driver reads the chipset from PMC_BOOT_0 after it owns the GPU's register window. The catalog JSON lists the GSP-RM requests for each chipset.\n\n\
         | Chipset | Name | Architecture | Display engine |\n\
         | --- | --- | --- | --- |\n",
    );
    for chip in &document.nvmodern_chipsets {
        let display = if chip.display { "Yes" } else { "No" };
        writeln!(
            output,
            "| `{}` | {} | {} | {} |",
            chip.chipset, chip.name, chip.architecture, display,
        )
        .expect("writing to a string cannot fail");
    }
    output
}

impl Catalog {
    pub fn run(self) -> Result<()> {
        let root = self
            .output_dir
            .unwrap_or_else(|| crate::tools::root().into());
        let document = document()?;
        let outputs = [
            ("DRIVERS.md", markdown(&document)),
            (
                "catalog.json",
                serde_json::to_string_pretty(&document)? + "\n",
            ),
        ];
        if !self.check {
            fs::create_dir_all(&root).with_context(|| format!("creating {}", root.display()))?;
        }
        for (name, content) in outputs {
            let path = root.join(name);
            if self.check {
                let old = fs::read_to_string(&path).with_context(|| {
                    format!("reading {}; run cargo xtask catalog", path.display())
                })?;
                ensure!(
                    old == content,
                    "{} is stale; run cargo xtask catalog",
                    path.display()
                );
            } else {
                fs::write(&path, content).with_context(|| format!("writing {}", path.display()))?;
            }
        }
        Ok(())
    }
}
