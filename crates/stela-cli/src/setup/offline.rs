//! Prepare host-side restore inputs on a connected computer and use them to
//! create a Northwood installer on a computer without network access.
use super::{
    Environment, InstallImage, Request,
    bundle::{self, Kind},
    create::staged,
    ecid::Ecid,
    firmware,
    prepare::{Prepared, PreparedSetup, prepare_restore_bundles, supported},
};
use crate::restore::{self, payload::Inventory};
use anyhow::{Context, Result, ensure};
use clap::Args;
use serde::{Deserialize, Serialize};
use std::{
    fs,
    io::Read,
    path::{Path, PathBuf},
};
use stela_formats::payload::{BLOCK_HASHES_FILE, MANIFEST_FILE, MAX_HASH_BLOCKS, PayloadManifest};

const KIT_FILE: &str = "offline-kit.json";
const BOOT_DIRECTORY: &str = "boot";
pub(super) const FIRMWARE_DIRECTORY: &str = "firmware";
const KIT_SCHEMA: u32 = 1;

#[derive(Args)]
pub(super) struct Prepare {
    /// A complete macOS restore IPSW.
    #[arg(long)]
    pub(super) ipsw: PathBuf,
    /// A new directory for the prepared kit. Keep the IPSW alongside it.
    #[arg(long)]
    pub(super) output: PathBuf,
    /// The Mac model to present.
    #[arg(long, default_value = super::PINNED_MODEL)]
    pub(super) model: String,
    /// Reuse the specified machine identity. A new ECID is generated by default.
    #[arg(long, value_parser = |value: &str| Ecid::parse(value).map_err(|error| error.to_string()))]
    pub(super) ecid: Option<Ecid>,
    /// Stage firmware for a target NVIDIA chip such as ga104. Repeat for multiple chips.
    #[arg(long, value_name = "CHIP")]
    pub(super) gpu: Vec<String>,
}

#[derive(Serialize, Deserialize)]
struct Metadata {
    schema_version: u32,
    model: String,
    build: String,
    ecid: Ecid,
    boot_sha256: String,
    payload_sha256: String,
    gpu: Vec<String>,
}

impl Prepare {
    pub(super) fn run(&self, environment: &Environment<'_>) -> Result<String> {
        let Self {
            ipsw,
            output,
            model,
            ecid,
            gpu,
        } = self;
        ensure!(!output.exists(), "{} already exists", output.display());
        let parent = output
            .parent()
            .filter(|path| !path.as_os_str().is_empty())
            .unwrap_or(Path::new("."));
        let temporary = tempfile::tempdir_in(parent)?;
        super::check_model(environment.models, model)?;
        super::image_is_remote(ipsw, Some(InstallImage::Full))?;
        let gpu = if gpu.is_empty() {
            firmware::host_chips(environment.host)?
                .0
                .into_iter()
                .map(str::to_owned)
                .collect()
        } else {
            gpu.clone()
        };
        let root = temporary.path();
        firmware::cache_gpu(&gpu, &root.join(FIRMWARE_DIRECTORY))?;
        let ecid = ecid.map_or_else(Ecid::generate, Ok)?;
        let (_, build, bundles) = prepare_restore_bundles(environment, ipsw, model, ecid)?;
        let [bundle] = bundles.as_slice() else {
            anyhow::bail!("the offline kit requires one macOS erase-restore bundle");
        };
        ensure!(
            bundle.kind == Kind::Restore && staged(&bundle.path()),
            "Apple did not return every signing answer required for offline installation"
        );
        let inventory = (environment.inventory)(ipsw, model)?;
        ensure!(
            inventory.manifest.product_build == build && inventory.manifest.model == *model,
            "the restore image changed while preparing the kit"
        );
        let boot_sha256 = bundle::install(&bundle.path(), &root.join(BOOT_DIRECTORY))?;
        let boot_problems = bundle::verify(&root.join(BOOT_DIRECTORY), &boot_sha256);
        ensure!(
            boot_problems.is_empty(),
            "the boot bundle did not read back as written: {}",
            boot_problems.join("; ")
        );
        let payload = inventory.manifest.to_json();
        let metadata = Metadata {
            schema_version: KIT_SCHEMA,
            model: model.clone(),
            build,
            ecid,
            boot_sha256,
            payload_sha256: stela_formats::sha256(payload.as_bytes()),
            gpu,
        };
        fs::write(root.join(MANIFEST_FILE), payload)?;
        fs::write(root.join(BLOCK_HASHES_FILE), inventory.blocks)?;
        fs::write(root.join(KIT_FILE), serde_json::to_vec_pretty(&metadata)?)?;
        fs::rename(root, output)
            .with_context(|| format!("publishing the offline kit to {}", output.display()))?;
        Ok(format!(
            "Prepared offline kit {} for macOS {} on {} (ECID {}). Keep {} with the kit.\n",
            output.display(),
            metadata.build,
            metadata.model,
            ecid,
            ipsw.display()
        ))
    }
}

pub(super) struct Ready {
    pub(super) bundles: PreparedSetup,
    pub(super) inventory: Inventory,
    pub(super) gpu: Vec<String>,
}

pub(super) fn load(
    root: &Path,
    request: &mut Request,
    environment: &Environment<'_>,
) -> Result<Ready> {
    let metadata: Metadata = serde_json::from_slice(&read(&root.join(KIT_FILE), 64 * 1024)?)?;
    ensure!(
        metadata.schema_version == KIT_SCHEMA,
        "unsupported offline kit version {}",
        metadata.schema_version
    );
    let path = root.join(BOOT_DIRECTORY);
    ensure!(
        path.symlink_metadata()?.is_dir(),
        "the kit boot path is not a directory"
    );
    for entry in fs::read_dir(&path)? {
        let entry = entry?;
        ensure!(
            entry.file_type()?.is_file(),
            "the kit boot path contains a non-file entry {}",
            entry.path().display()
        );
    }
    ensure!(
        !metadata.boot_sha256.is_empty(),
        "the kit has no boot bundle digest"
    );
    let problems = bundle::verify(&path, &metadata.boot_sha256);
    ensure!(
        problems.is_empty(),
        "the offline kit's boot bundle is damaged: {}",
        problems.join("; ")
    );
    let generation = bundle::generation(&path)?;
    ensure!(
        generation == environment.generation(),
        "the offline kit has boot bundle {generation}, but this build uses {}; prepare a new kit",
        environment.generation()
    );
    ensure!(
        staged(&path),
        "the offline kit's signing answers are incomplete"
    );
    let payload = read(&root.join(MANIFEST_FILE), 16 * 1024 * 1024)?;
    ensure!(
        stela_formats::sha256(&payload) == metadata.payload_sha256,
        "the offline kit's payload manifest failed its digest check"
    );
    let manifest = PayloadManifest::parse(&payload).map_err(|error| anyhow::anyhow!("{error}"))?;
    ensure!(
        manifest.product_build == metadata.build && manifest.model == metadata.model,
        "the offline kit's payload identifies a different build or Mac model"
    );
    let block_hashes = manifest
        .block_hashes
        .as_ref()
        .context("the offline kit's payload has no block hashes")?;
    let blocks = read(&root.join(BLOCK_HASHES_FILE), MAX_HASH_BLOCKS * 32)?;
    ensure!(
        block_hashes.file == BLOCK_HASHES_FILE
            && blocks.len() as u64 == manifest.hash_blocks() * 32
            && stela_formats::sha256(&blocks) == block_hashes.sha256,
        "the offline kit's payload block hashes failed verification"
    );
    let ipsw = request
        .ipsw
        .as_deref()
        .context("pass the kit's IPSW with --ipsw")?;
    super::image_is_remote(ipsw, Some(InstallImage::Full))?;
    let (version, build) = restore::payload::identity(ipsw, &metadata.model)?;
    ensure!(
        build == metadata.build && version == manifest.product_version,
        "{} belongs to macOS {version} ({build}), but the kit is for {} ({})",
        ipsw.display(),
        manifest.product_version,
        metadata.build
    );
    supported(environment, ipsw, &build)?;
    super::check_model(environment.models, &metadata.model)?;
    let progress =
        crate::progress::Phase::bytes("Verifying the offline restore image", manifest.source.bytes);
    let (bytes, sha256) =
        restore::payload::file_sha256_with(ipsw, |bytes| progress.advance(bytes))?;
    progress.finish();
    ensure!(
        bytes == manifest.source.bytes
            && manifest.source.sha256.as_deref() == Some(sha256.as_str()),
        "{} does not match the IPSW used to prepare the offline kit",
        ipsw.display()
    );
    let bundle = Prepared::existing(&path, build.clone(), metadata.ecid, generation)?;
    request.model = Some(metadata.model);
    request.ecid = Some(metadata.ecid);
    request.install_image = Some(InstallImage::Full);
    request.fetch = false;
    Ok(Ready {
        bundles: (version, build, vec![bundle]),
        inventory: Inventory {
            report: serde_json::Value::Null,
            manifest,
            blocks,
        },
        gpu: metadata.gpu,
    })
}

fn read(path: &Path, limit: u64) -> Result<Vec<u8>> {
    let metadata = path
        .symlink_metadata()
        .with_context(|| format!("reading {}", path.display()))?;
    ensure!(
        metadata.is_file(),
        "{} is not a regular file",
        path.display()
    );
    let mut bytes = Vec::new();
    fs::File::open(path)?
        .take(limit + 1)
        .read_to_end(&mut bytes)?;
    ensure!(
        bytes.len() as u64 <= limit,
        "{} is too large",
        path.display()
    );
    Ok(bytes)
}
